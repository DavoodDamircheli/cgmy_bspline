"""
Step 11 — Calibration: fit CGMY parameters to a synthetic IV surface.

True parameters (Set ii): C=0.1, G=2.0, M=3.5, Y=1.5.
IVs are generated by the COS pricer (N_cos=2048), then the calibrator
recovers C,G,M,Y from scratch using two-phase DE + L-BFGS-B.

Outputs
-------
  • cgmy_bspline/results/table_calibration_insample.txt
  • cgmy_bspline/results/table_calibration_speed.txt
"""
import os
import time
import numpy as np

from cgmy_bspline.src.cgmy_params import CGMYParams as SrcParams
from cgmy_bspline.src.cos_pricer import cos_put_price
from cgmy_bspline.greeks import bs_implied_vol
from cgmy_bspline.calibration import CGMYCalibrator

# ── True parameters ───────────────────────────────────────────────────────────
TRUE = dict(C=0.1, G=2.0, M=3.5, Y=1.5)
R    = 0.1
K_REF = 100.0

# ── Calibration surface grid ──────────────────────────────────────────────────
# 5 maturities × 6 strikes  (near-ATM, liquid region)
STRIKES    = np.array([90.0, 95.0, 100.0, 105.0, 110.0, 115.0])
MATURITIES = [0.1, 0.2, 0.3, 0.5, 0.75]

# ── Calibrator settings (fast demo) ──────────────────────────────────────────
N_CAL  = 64           # spatial intervals for the calibrator
BW_CAL = 32           # bandwidth
DE_KW  = dict(popsize=6, maxiter=80, seed=0, tol=1e-4, polish=False)


def generate_synthetic_surface():
    """COS put prices → Black-Scholes IVs for the true CGMY parameters."""
    n_T, n_K = len(MATURITIES), len(STRIKES)
    iv_mat = np.full((n_T, n_K), np.nan)
    print("Generating synthetic IV surface from COS pricer...")
    for i, T_i in enumerate(MATURITIES):
        for j, K_j in enumerate(STRIKES):
            p = SrcParams(
                C=TRUE['C'], G=TRUE['G'], M=TRUE['M'], Y=TRUE['Y'],
                r=R, T=T_i, K=K_REF, S0=K_j,
            )
            price = cos_put_price(p, N_cos=2048)
            iv = bs_implied_vol(price, S=K_j, K=K_REF, T=T_i, r=R)
            iv_mat[i, j] = iv
    return iv_mat


def run_calibration(market_ivs):
    print("\nInitialising calibrator...")
    cal = CGMYCalibrator(
        market_ivs=market_ivs,
        strikes=STRIKES,
        maturities=MATURITIES,
        r=R,
        S0=K_REF,
        K_ref=K_REF,
        N=N_CAL,
        bandwidth=BW_CAL,
    )

    print(f"Running two-phase optimisation  (N={N_CAL}, DE popsize={DE_KW['popsize']}, "
          f"maxiter={DE_KW['maxiter']})...")
    t0 = time.perf_counter()
    result = cal.calibrate(de_kwargs=DE_KW)
    result['cpu_total'] = time.perf_counter() - t0
    return result


def print_and_save(market_ivs, result):
    C_hat = result['C']
    G_hat = result['G']
    M_hat = result['M']
    Y_hat = result['Y']
    rmse  = result['rmse_vol']
    n_ev  = result['n_func_evals']
    cpu   = result['cpu_total']

    sep = "=" * 60
    in_sample_lines = [
        sep,
        "=== Calibration: In-Sample Report ===",
        sep,
        "",
        f"  True params:       C={TRUE['C']:.3f}  G={TRUE['G']:.3f}  "
        f"M={TRUE['M']:.3f}  Y={TRUE['Y']:.3f}",
        f"  Recovered params:  C={C_hat:.3f}  G={G_hat:.3f}  "
        f"M={M_hat:.3f}  Y={Y_hat:.3f}",
        "",
        f"  In-sample RMSE (IV): {rmse:.6f}",
        f"  Function evals:      {n_ev}",
        f"  CPU time:            {cpu:.1f}s",
        "",
        "  IV fit (model vs market):",
        f"  {'T':>5}  {'K':>6}  {'IV_market':>10}  {'IV_model':>10}  {'err':>10}",
        "  " + "-" * 46,
    ]

    # Rebuild model IVs at recovered parameters
    from cgmy_bspline.parameters import CGMYParams as OldParams
    from cgmy_bspline.solver_cn import solve_cn
    from cgmy_bspline.grid import make_grid
    from cgmy_bspline.projection import eval_solution

    model_iv_lines = []
    max_err = 0.0
    for i, T_i in enumerate(MATURITIES):
        old_p = OldParams(C=C_hat, G=G_hat, M=M_hat, Y=Y_hat, r=R, K=K_REF, T=T_i)
        N_tau = max(10, round(200 * T_i))
        res = solve_cn(old_p, N=128, p=3, N_tau=N_tau, bandwidth=128)
        g = make_grid(old_p, 128)
        x_ev = np.log(STRIKES)
        prices = eval_solution(res['c_final'], g, 3, x_ev)
        for j, (K_j, pr) in enumerate(zip(STRIKES, prices)):
            iv_m = bs_implied_vol(pr, S=K_j, K=K_REF, T=T_i, r=R)
            err = abs(iv_m - market_ivs[i, j]) if not np.isnan(iv_m) else float('nan')
            max_err = max(max_err, err) if not np.isnan(err) else max_err
            row = (f"  {T_i:>5.2f}  {K_j:>6.0f}  "
                   f"{market_ivs[i,j]:>10.4f}  {iv_m:>10.4f}  {err:>10.4f}")
            in_sample_lines.append(row)

    in_sample_lines += [
        "  " + "-" * 46,
        f"  Max pointwise IV error: {max_err:.4f}",
        sep,
    ]

    for ln in in_sample_lines:
        print(ln)

    path_in = "cgmy_bspline/results/table_calibration_insample.txt"
    with open(path_in, "w") as f:
        f.write("\n".join(in_sample_lines))
    print(f"\nSaved: {path_in}")

    # Speed table
    speed_lines = [
        sep,
        "=== Calibration: Speed Summary ===",
        sep,
        f"  Grid size N:         {N_CAL}",
        f"  Bandwidth:           {BW_CAL}",
        f"  Strikes:             {len(STRIKES)}",
        f"  Maturities:          {len(MATURITIES)}",
        f"  DE popsize:          {DE_KW['popsize']}",
        f"  DE maxiter:          {DE_KW['maxiter']}",
        f"  Total function evals:{n_ev}",
        f"  CPU time:            {cpu:.1f}s",
        f"  Avg time/eval:       {1000*cpu/max(n_ev,1):.1f}ms",
        f"  In-sample RMSE:      {rmse:.6f}",
        sep,
    ]
    for ln in speed_lines:
        print(ln)

    path_sp = "cgmy_bspline/results/table_calibration_speed.txt"
    with open(path_sp, "w") as f:
        f.write("\n".join(speed_lines))
    print(f"Saved: {path_sp}")


def main():
    os.makedirs("cgmy_bspline/results", exist_ok=True)

    market_ivs = generate_synthetic_surface()
    print("\nMarket IV surface:")
    header = f"  {'T':>5}  " + "  ".join(f"K={K:.0f}" for K in STRIKES)
    print(header)
    for i, T_i in enumerate(MATURITIES):
        row = f"  {T_i:>5.2f}  " + "  ".join(f"{market_ivs[i,j]:.4f}" for j in range(len(STRIKES)))
        print(row)

    result = run_calibration(market_ivs)
    print_and_save(market_ivs, result)


if __name__ == "__main__":
    main()
